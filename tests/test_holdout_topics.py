def _topic(before_ctx, old, new):
    after_ctx = before_ctx.replace(old, new, 1)
    ch = Change(kind="replace", before=old, after=new, context=before_ctx, context_after=after_ctx)
    from pravki.textdiff import flags_for_change
    ch.flags = flags_for_change(old, new)
    return classify(ch).topic


def test_holdout_topic_accuracy():
    wrong = []
    for ctx, old, new, want in CASES:
        got = _topic(ctx, old, new)
        if got != want:
            wrong.append((want, got, ctx[:60]))
    acc = 1 - len(wrong) / len(CASES)
    print(f"\nHOLDOUT topic accuracy: {acc:.0%} ({len(CASES) - len(wrong)}/{len(CASES)})")
    for w in wrong:
        print("  ", w)
    # это не цель, а страховка от деградации: порог поставлен ниже достигнутого
    assert acc >= 0.5
